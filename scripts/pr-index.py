#!/usr/bin/env python3
"""Regenerate docs/pr-index.md, the table of contents of every pull request.

Usage: python3 scripts/pr-index.py [--repo owner/name] [--out docs/pr-index.md]

The number, title, state and date of each PR come from the GitHub API. The
summary, feature area, place in the app and main files come from
docs/pr-index-notes.json; a PR with no notes there gets the first sentence of
its description, an area guessed from its title and its most-changed files,
and is marked "auto" until someone writes its notes.

Set GITHUB_TOKEN to raise the API rate limit (the GitHub Action does).
Uses only the standard library.
"""

import argparse
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTES = os.path.join(ROOT, "docs", "pr-index-notes.json")

# Keyword guesses for PRs that have no notes yet, tried in order.
GUESSES = [
    ("Editing and warping", r"\b(edit|warp|quantize|stretch|slice|repair)"),
    ("Modes, tunings and composition", r"\b(mode|modal|tuning|raga|rāg|maqam|dastgah|counterpoint|fugue|rhythm|tāl|stochastic|scale)"),
    ("Φ effects and sounds", r"(Φ|\bphi (eq|echo|space|compressor|phaser|chorus|limiter))"),
    ("Spatial audio", r"\b(ambisonic|spatial|binaural|speaker|surround)"),
    ("Analysis and meters", r"\b(analy[sz]|meter|loudness|spectr|scope)"),
    ("Mastering", r"\b(master|mastering|limiter|dither)"),
    ("Routing and racks", r"\b(patchbay|prism|routing|rack)"),
    ("Trackers", r"\btracker"),
    ("Performance and visuals", r"\b(performance|visuali[sz]er|video|stream|control surface|launchpad|push)"),
    ("Mixer and clip launcher", r"\b(mixer|clip|launcher|track|recording|loop)"),
    ("Instruments and plugins", r"\b(instrument|plugin|sampler|synth|cardinal|airwindows|clap|vst)"),
    ("Documentation", r"\b(manual|docs?|documentation|readme)"),
    ("Interface and branding", r"\b(ui|panel|theme|window|menu|shortcut|rename|logo)"),
]
UNSORTED = "Not yet sorted"


def api(repo, path, token):
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}/{path}")
    req.add_header("Accept", "application/vnd.github+json")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def all_prs(repo, token):
    prs, page = [], 1
    while True:
        batch = api(repo, f"pulls?state=all&per_page=100&page={page}", token)
        prs += batch
        if len(batch) < 100:
            return prs
        page += 1


def first_sentence(body):
    for line in (body or "").splitlines():
        line = line.strip()
        if not line or line.startswith(("<!--", "_Requested", "#", "!", "|", "---", "```")):
            continue
        line = re.sub(r"\*\*|`|\[([^\]]*)\]\([^)]*\)", lambda m: m.group(1) or "", line).lstrip("-* ")
        if re.match(r"(this pr is )?(stacked|follow-up|builds on|this follows|this is stacked)", line, re.I):
            continue
        m = re.match(r"(.+?[.!?])(\s+[A-Z(\"]|$)", line)
        text = m.group(1) if m else line
        return text if len(text) <= 160 else text[:157].rstrip() + "..."
    return ""


def guess_where(body):
    """A bold menu path in the description, such as **Mixer > Patchbay**."""
    m = re.search(r"\*\*([^*\n]{2,40}\s[>›]\s[^*\n]{2,60})\*\*", body or "")
    return m.group(1) if m else ""


def guess_area(title):
    for area, pattern in GUESSES:
        if re.search(pattern, title, re.I):
            return area
    return UNSORTED


def main_files(repo, number, token):
    files = api(repo, f"pulls/{number}/files?per_page=100", token)
    files = [f for f in files if not f["filename"].startswith(("third_party/", "docs/screenshots/"))]
    files.sort(key=lambda f: f["changes"], reverse=True)
    return [f["filename"] for f in files[:3]]


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def state_of(pr):
    if pr.get("merged_at"):
        return "merged", pr["merged_at"][:10]
    if pr["state"] == "open":
        return ("draft" if pr.get("draft") else "open"), pr["created_at"][:10]
    return "closed", (pr.get("closed_at") or pr["created_at"])[:10]


def render(repo, rows, areas):
    counts = {s: sum(1 for r in rows if r["state"] == s) for s in ("merged", "open", "draft", "closed")}
    out = [
        "# PHI pull request index",
        "",
        "Every pull request in this repository: what it added, where to find it in the app and in the code.",
        "",
        "This file is generated by `scripts/pr-index.py` and kept current by the `pr-index` GitHub Action,",
        "which runs whenever a pull request is opened, edited, merged or closed. Don't edit it by hand:",
        "to change a summary, area or location, edit `docs/pr-index-notes.json`.",
        "Lines marked *auto* were filled in from the PR itself and are waiting for notes.",
        "",
        f"**{len(rows)} pull requests:** {counts['merged']} merged, {counts['open'] + counts['draft']} open"
        + (f", {counts['closed']} closed without merging" if counts["closed"] else "") + ".",
        "",
        "## Contents",
        "",
        "- [By feature area](#by-feature-area)",
    ]
    present = [a for a in areas if any(r["area"] == a for r in rows)]
    for a in present:
        out.append(f"  - [{a}](#{anchor(a)})")
    out += ["- [By number](#by-number)", "", "## By feature area", ""]
    for a in present:
        out += [f"### {a}", "", "| PR | Title | State | In the app | In the code |", "|---|---|---|---|---|"]
        for r in (r for r in rows if r["area"] == a):
            out.append(f"| {link(repo, r)} | {cell(r['title'])} | {r['state']} | {cell(r['where'])} | {code(r['files'])} |")
        out.append("")
    out += ["## By number", "", "| PR | Title | What it added | State | Date | Area |", "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: r["number"]):
        summary = cell(r["summary"]) + (" *(auto)*" if r["auto"] else "")
        out.append(f"| {link(repo, r)} | {cell(r['title'])} | {summary} | {r['state']} | {r['date']} | {r['area']} |")
    out.append("")
    return "\n".join(out)


def anchor(heading):
    return re.sub(r"[^\w\- ]", "", heading.lower()).strip().replace(" ", "-")


def link(repo, r):
    return f"[#{r['number']}](https://github.com/{repo}/pull/{r['number']})"


def code(files):
    return "<br>".join(f"`{f}`" for f in files)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "phinyx852Hz/audio-editor"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "pr-index.md"))
    args = ap.parse_args()
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")

    with open(NOTES, encoding="utf-8") as f:
        notes = json.load(f)
    areas = notes["areas"] + [UNSORTED]

    rows = []
    for pr in all_prs(args.repo, token):
        n = pr["number"]
        note = notes["prs"].get(str(n), {})
        state, date = state_of(pr)
        rows.append({
            "number": n,
            "title": pr["title"],
            "state": state,
            "date": date,
            "auto": "summary" not in note,
            "summary": note.get("summary") or first_sentence(pr.get("body")),
            "area": note.get("area") if note.get("area") in areas else guess_area(pr["title"]),
            "where": note.get("where") or guess_where(pr.get("body")),
            "files": note.get("files") or main_files(args.repo, n, token),
        })
    rows.sort(key=lambda r: r["number"])

    text = render(args.repo, rows, areas)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(args.out, ROOT)}: {len(rows)} pull requests", file=sys.stderr)


if __name__ == "__main__":
    main()
