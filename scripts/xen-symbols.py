#!/usr/bin/env python3
"""Write Source/core/XenSymbols.inc: Xen Tuner's accidental symbol codes with their SMuFL code points.

Usage: python3 scripts/xen-symbols.py <musescore-xen-tuner>/"Xen Tuner/generated-tables.js" \
           <smufl>/metadata/glyphnames.json > Source/core/XenSymbols.inc

Xen Tuner (euwbah, GPL-3.0-or-later) numbers every accidental symbol it knows (CODE_TO_LABELS, a
list of SMuFL names, and MuseScore's for some) and gives many a text code ("#", "bb", "\\!)" for
Sagittal); a tuning config names its accidentals by either. The SMuFL glyph names
(w3c/smufl metadata/glyphnames.json) give each name its code point, which PHI draws in Bravura.
Uses only the standard library.
"""

import ast
import json
import re
import sys


def main():
    tables = open(sys.argv[1], encoding="utf-8").read()
    glyphs = json.load(open(sys.argv[2], encoding="utf-8"))

    labels_src = tables[tables.index("var CODE_TO_LABELS"):tables.index("var TEXT_TO_CODE")]
    rows = re.findall(r"^\s*(null|\[.*\]),?\s*$", labels_src, re.M)
    texts_src = tables[tables.index("var TEXT_TO_CODE"):tables.index("var SYMBOL_LAYOUT")]
    texts = re.findall(r"""^\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"):\s*(\d+),?\s*$""", texts_src, re.M)

    text_of = {}
    for literal, code in texts:
        text_of.setdefault(int(code), ast.literal_eval(literal))

    def cpp(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    print("// SPDX-License-Identifier: GPL-3.0-or-later")
    print("// Generated by scripts/xen-symbols.py from Xen Tuner's Xen Tuner/generated-tables.js")
    print("// (Copyright (C) 2023 euwbah, GPL-3.0-or-later) and the SMuFL glyph names. Do not edit.")
    print("// XEN_SYMBOL (code point (0: none in SMuFL), SMuFL name, text code), by Xen Tuner's symbol code;")
    print("// then XEN_TEXT (text code, symbol code) for every text code.")
    for code, row in enumerate(rows):
        if row == "null":
            print('XEN_SYMBOL (0, "", "")')
            continue
        names = ast.literal_eval(row)
        point, name = 0, names[0]
        for n in names:
            if n in glyphs:
                point, name = int(glyphs[n]["codepoint"][2:], 16), n
                break
        print("XEN_SYMBOL (0x%04X, %s, %s)" % (point, cpp(name), cpp(text_of.get(code, ""))))
    for literal, code in texts:
        print("XEN_TEXT (%s, %d)" % (cpp(ast.literal_eval(literal)), int(code)))


if __name__ == "__main__":
    main()
