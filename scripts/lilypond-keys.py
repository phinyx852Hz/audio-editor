"""Writes Source/mixer/KeySignatures.inc from LilyPond's ly/arabic.ly, ly/turkish-makam.ly and
ly/persian.ly (GPL-3.0-or-later; Amir Czwink and Neil Puttock, Adam Good, Kees van den Doel and
Werner Lemberg): each maqam's, makam's and dastgah's key signature, and the order a key signature
writes its accidentals in.

    python3 scripts/lilypond-keys.py path/to/lilypond/ly > Source/mixer/KeySignatures.inc

A key signature is LilyPond's: an alteration for each of the seven letters of a scale on C (C is
0, B 6), which LilyPond moves to the key's tonic. Alterations are written in cents: LilyPond's
are fractions of a whole tone (a flat -1/2), 200 cents to the tone for Arabic and Persian; the
Turkish ones are Arel-Ezgi-Uzdilek commas (the file's comments give each in ninths of a tone, a
koma 1/9), 1200/53 cents each, as PHI's 53-comma Turkish staff has them."""
import re
import sys
from fractions import Fraction

def alist (body, values):
    out = [0.0] * 7
    for degree, value in re.findall (r"\(\s*(\d)\s*\.\s*,\s*(\(-\s*[A-Z-]+\)|[A-Z-]+)\s*\)", body):
        neg = value.startswith ("(-")
        name = value.strip ("()- ").strip() if neg else value
        if name not in values:
            raise SystemExit ("unknown alteration " + value)
        if int (degree) > 6:
            continue   # sivenuma's (7 . -BAKIYE): no eighth letter; LilyPond reads past it too
        out[int (degree)] = -values[name] if neg else values[name]
    return out

def main():
    root = sys.argv[1]
    tone = 200.0
    base = { "NATURAL": 0.0, "FLAT": -tone / 2, "SHARP": tone / 2, "SEMI-FLAT": -tone / 4, "SEMI-SHARP": tone / 4,
             "DOUBLE-FLAT": -tone, "DOUBLE-SHARP": tone, "THREE-Q-FLAT": -3 * tone / 4, "THREE-Q-SHARP": 3 * tone / 4 }
    rows = []
    orders = {}

    def keys (text, tradition, values):
        for name, body in re.findall (r"^([A-Za-z_]+)\s*=\s*#`\((.*?)\n\s*\)", text, re.M | re.S):
            if "make-pitch" in body or "Order" in name or not re.search (r"\(\s*\d\s*\.", body):
                continue
            rows.append ((tradition, name, "", alist (body, values)))

    def order (text, name, values, tradition):
        m = re.search (name + r"\s*=\s*#`\((.*?)\n\s*\)", text, re.S)
        if m:
            orders[tradition] = [(int (d), (-values[v.strip ("()- ")] if v.startswith ("(-") else values[v])) for d, v in
                                 re.findall (r"\(\s*(\d)\s*\.\s*,\s*(\(-\s*[A-Z-]+\)|[A-Z-]+)\s*\)", m.group (1))]

    arabic = open (root + "/arabic.ly", encoding="utf-8").read()
    keys (arabic.split ("TwentyFourTETglyphs")[0], "arabic", base)
    order (arabic, "keyAlterationOrder", base, "arabic")

    persian = open (root + "/persian.ly", encoding="utf-8").read()
    pvalues = dict (base, KORON=-0.3 * tone, SORI=0.2 * tone, VLAT=-0.1 * tone, FVLAT=-0.6 * tone, SVLAT=0.4 * tone)
    keys (persian.split ("Define Persian tunings")[1], "persian", pvalues)
    order (persian, "persianKeyAlterationOrder", pvalues, "persian")

    turkish = open (root + "/turkish-makam.ly", encoding="utf-8").read()
    comma = 1200.0 / 53
    ninths = { "KOMA": 1, "CEYREK": Fraction (9, 4), "EKSIK-BAKIYE": 3, "BAKIYE": 4, "KUCUK": 5, "BUYUKMUCENNEB": 8, "TANINI": 9 }
    tvalues = dict (base, **{ k: float (v) * comma for k, v in ninths.items() })
    shapes = {}
    aliases = []
    for line in turkish.split ("key signature definitions")[1].splitlines():
        m = re.match (r"^([A-Za-z_]+)\s*=\s*#`\((.*)\)\s*%\s*(?:\\key\s+)?([a-g])", line)
        if m:
            shapes[m.group (1)] = alist (m.group (2), tvalues)
            rows.append (("turkish", m.group (1), m.group (3), shapes[m.group (1)]))
            continue
        m = re.match (r"^([A-Za-z_]+)\s*=\s*\\([A-Za-z_]+)\s*%\s*(?:\\key\s+)?([a-g])", line)
        if m:
            aliases.append (m.groups())
    # A name given another's key signature, in any order.
    while aliases:
        left = []
        for name, same, tonic in aliases:
            if same in shapes:
                shapes[name] = shapes[same]
                rows.append (("turkish", name, tonic, shapes[same]))
            else:
                left.append ((name, same, tonic))
        if len (left) == len (aliases):
            raise SystemExit ("unresolved: " + ", ".join (a[0] for a in left))
        aliases = left

    print ("// SPDX-License-Identifier: GPL-3.0-or-later")
    print ("// Generated by scripts/lilypond-keys.py from LilyPond's ly/arabic.ly (C) 2017-2026 Amir Czwink,")
    print ("// (C) 2008 Neil Puttock; ly/turkish-makam.ly (C) 2019-2026 Adam Good; ly/persian.ly (C) 2009-2021")
    print ("// Kees van den Doel, (C) 2021-2026 Werner Lemberg. All GPL-3.0-or-later. Do not edit.")
    print ("// PHI_KEY (tradition, LilyPond's name, the tonic its comment gives or \"\", cents for C D E F G A B)")
    for tradition, name, tonic, cents in rows:
        print ('PHI_KEY ("%s", "%s", "%s", { %s })' % (tradition, name, tonic, ", ".join ("%.4f" % c for c in cents)))
    print ("// PHI_ORDER (tradition, letter (C 0 .. B 6), cents): the order a key signature is written in")
    for tradition, items in orders.items():
        for d, c in items:
            print ('PHI_ORDER ("%s", %d, %.4f)' % (tradition, d, c))

main()
